"""Japanese Hiragana and Katakana for the Yisu fonts, drawn as original
centre-line strokes on the 1000 x 1000 grid (y down).

Stroke order follows Japan's official school curriculum (文部科学省 学習指導要領).
Voiced (dakuten ゛) and semi-voiced (handakuten ゜) forms compose their base
glyph with standard upper-right marks; small kana scale their base to ~72%
anchored slightly lower-left/centred for natural mixed CJK-Japanese typesetting.
"""


def S(spec):
    out = []
    for part in spec.split(';'):
        part = part.strip()
        if part:
            out.append((part[0], part[1:].strip()))
    return out


def box(*parts):
    return ('box', list(parts))


FULL = (0, 0, 1000, 1000)
SMALL_BOX = (120, 230, 860, 960)

# Dakuten (゛) and Handakuten (゜) in the upper-right corner of the 1000 grid.
DAKUTEN = S('D M760 110 C800 150 830 190 855 245; D M850 80 C890 120 920 160 945 215')
HANDAKUTEN = S('E M845 100 C910 100 940 140 940 195 C940 250 905 290 845 290 '
               'C785 290 750 250 750 195 C750 140 785 100 845 100')


def dakuten(base):
    return box((base, (0, 0, 920, 1000)), (DAKUTEN, FULL))


def handakuten(base):
    return box((base, (0, 0, 920, 1000)), (HANDAKUTEN, FULL))


def small(base):
    return box((base, SMALL_BOX))


