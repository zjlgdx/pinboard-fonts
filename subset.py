"""Write the Yisu fonts, each cut down to the letters it draws, as a
TypeScript module of WOFF2 data URIs for use inside an SVG.

Reads JSON from stdin, {"BALLPOINT": "text…", "MARKER": …, "TYPEWRITER": …}
(the Pinboard theme still names the fonts by their old nicknames):

    node board-text.mjs | .venv/bin/python subset.py ../mockups/fonts5.ts
"""
import base64
import io
import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

OUT = Path(__file__).resolve().parent / 'out'
FONTS = {'BALLPOINT': 'YisuHuasha', 'MARKER': 'YisuLouhen', 'TYPEWRITER': 'YisuYinni'}

texts = json.load(sys.stdin)
lines = ["// Generated by fontkit/subset.py: the Yisu fonts, each cut down to",
         '// the letters the board draws with it, as WOFF2 data URIs.', '']
for const, stem in FONTS.items():
    font = TTFont(OUT / f'{stem}-Regular.otf')
    opts = subset.Options()
    opts.flavor = 'woff2'
    # Kerning and the combining marks (ccmp's dotless i and .case marks, mark
    # and mkmk's anchors), but not the alternates: labels are short.
    opts.layout_features = ['kern', 'ccmp', 'mark', 'mkmk']
    opts.name_IDs = [1]
    # The board's SVG ignores hints; plain charstrings compress best.
    opts.hinting = False
    opts.desubroutinize = True
    sub = subset.Subsetter(opts)
    sub.populate(text=texts.get(const, '') + ' ')
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    b64 = base64.b64encode(buf.getvalue()).decode()
    lines.append(f"export const {const} = 'data:font/woff2;base64,{b64}'")
    print(f'{stem}: {len(b64)} chars', file=sys.stderr)
Path(sys.argv[1]).write_text('\n'.join(lines) + '\n')
