"""The Chinese characters Pinboard draws, as strokes and components.

Grid: 1000 x 1000, y down; the frame is the character's face. A stroke is
'K path', K its kind (see hanzi.py: E even, P lifting, G hooked, N 捺, D 點).
Strokes are separated by ';'.

Components that sit at the left of a character (亻 氵 扌 …) are drawn in
place, in the full grid, as the left part of a character: they're added to
a right part placed in its own box, so neither is squeezed out of shape.
Everything here is drawn for this font from what the characters are.
"""


def S(spec):
    out = []
    for part in spec.split(';'):
        part = part.strip()
        if part:
            out.append((part[0], part[1:].strip()))
    return out


def box(*parts):
    """Components placed in boxes: box((comp, (x0, y0, x1, y1)), …)."""
    return ('box', list(parts))


FULL = (0, 0, 1000, 1000)
RIGHT = (330, 0, 1000, 1000)          # the right part beside a left component


def lr(left, right, at=RIGHT):
    """A left component drawn in place, and a right part in its box."""
    return box((left, FULL), (right, at))


