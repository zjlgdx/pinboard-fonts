"""Write the board's letters as SVG outlines, for a surface that won't load
fonts: a TypeScript module of compact glyph paths, advances and kerning.

The desktop app strips fonts embedded in a backdrop SVG, so the board draws
its labels as <path>s instead. Each letter is drawn once in <defs> and
placed with <use>. The outlines are re-traced from the same pens with
stronger smoothing (and the typewriter without its ribbon texture, which
can't be seen at label sizes), so they cost few points; advances and
kerning come from the built fonts.

Reads {"hand": "text…", "mk": …, "type": …} on stdin:

    node ../mockups/board-text.mjs | .venv/bin/python outline.py ../mockups/glyphs5.ts
"""
import json
import sys
import tempfile
from pathlib import Path

from PIL import Image
from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

import build
import cells

OUT = Path(__file__).resolve().parent / 'out'
PENS = {'hand': ('ballpoint', 'PinboardBallpoint'), 'mk': ('marker', 'PinboardMarker'),
        'type': ('typewriter', 'PinboardTypewriter')}
GRID = 5        # font units per path unit: 1/200 em


class CompactPen(BasePen):
    """SVG path data in relative commands on a coarse integer grid."""

    def __init__(self):
        super().__init__(None)
        self.parts, self.cur = [], (0, 0)

    def _q(self, p):
        return round(p[0] / GRID), round(-p[1] / GRID)

    def _rel(self, *pts):
        out, (cx, cy) = [], self.cur
        for p in pts:
            x, y = self._q(p)
            out += [x - cx, y - cy]
        return out

    @staticmethod
    def _nums(ns):
        s = ''
        for n in ns:
            t = str(n)
            s += t if (t.startswith('-') or not s) else ' ' + t
        return s

    def _moveTo(self, p):
        x, y = self._q(p)
        self.parts.append('M' + self._nums([x, y]))
        self.cur = (x, y)

    def _lineTo(self, p):
        r = self._rel(p)
        if r != [0, 0]:
            self.parts.append('l' + self._nums(r))
            self.cur = self._q(p)

    def _curveToOne(self, p1, p2, p3):
        r = self._rel(p1, p2, p3)
        if any(r):
            self.parts.append('c' + self._nums(r))
            self.cur = self._q(p3)

    def _closePath(self):
        self.parts.append('z')

    def d(self):
        return ''.join(self.parts)


def bounds(rec):
    bp = BoundsPen(None)
    rec.replay(bp)
    return bp.bounds


def coarse(style_key, ch, tmp):
    """The letter re-traced smooth, before spacing (font units)."""
    style = build.STYLES[style_key]()
    if style_key == 'typewriter':
        style.ink = lambda img, rng: img          # no ribbon texture at label size
    img = Image.new('L', (int(build.W * build.S), int(build.H * build.S)), 0)
    img = style.draw(ch, img, 0)
    return build.trace(img, tmp, 400, (4.0, '2.0'))


def main():
    texts = json.load(sys.stdin)
    lines = ["// Generated by fontkit/outline.py: the board's letters as outlines, in",
             f"// units of {GRID / 1000:g} em, y down, origin on the baseline at the pen's start.",
             "// adv: advances; kern: pair adjustments; d: path data.",
             'export const GLYPHS: Record<"hand" | "mk" | "type", { adv: Record<string, number>; kern: Record<string, number>; d: Record<string, string> }> = {']
    total = 0
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        for cls, (style_key, stem) in PENS.items():
            chars = sorted(set(texts.get(cls, '')))
            font = TTFont(OUT / f'{stem}-Regular.otf')
            gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font['hmtx']
            adv, d = {}, {}
            # Box drawing, blocks and Powerline separators are cell geometry
            # (cells.py), not pen strokes: the font's outline is already exact.
            # Only which characters cells.py draws matters here, not the sizes.
            os2 = font['OS/2']
            cell = set(cells.glyphs(build.Typewriter.advance, os2.sTypoAscender, os2.sTypoDescender, 80)) \
                if style_key == 'typewriter' else set()
            for ch in chars:
                name = cmap[ord(ch)]
                adv[ch] = round(hmtx[name][0] / GRID, 1)
                if ch == ' ':
                    continue
                if ch in cell:
                    pen = CompactPen()
                    gs[name].draw(pen)
                    d[ch] = pen.d()
                    continue
                # Place the smooth outline where the font's own glyph sits:
                # spaced across, and lifted onto the baseline as the font is.
                bp = BoundsPen(gs)
                gs[name].draw(bp)
                rec = coarse(style_key, ch, tmp)
                cb = bounds(rec)
                dx = (bp.bounds[0] + bp.bounds[2]) / 2 - (cb[0] + cb[2]) / 2
                dy = (bp.bounds[1] + bp.bounds[3]) / 2 - (cb[1] + cb[3]) / 2
                pen = CompactPen()
                rec.replay(TransformPen(pen, (1, 0, 0, 1, dx, dy)))
                d[ch] = pen.d()
            kern, exact = {}, {}
            if 'GPOS' in font:
                names = {cmap[ord(c)]: c for c in chars if c != ' '}
                for lk in font['GPOS'].table.LookupList.Lookup:
                    if lk.LookupType != 2:      # pair kerning only, not mark attachment
                        continue
                    for st in lk.SubTable:
                        if getattr(st, 'Format', None) == 1:
                            # Glyph pairs (an accent under a T) come first in the
                            # lookup, so they win over the class pairs below.
                            for g1, ps in zip(st.Coverage.glyphs, st.PairSet):
                                if g1 not in names:
                                    continue
                                for r in ps.PairValueRecord:
                                    if r.SecondGlyph in names:
                                        v = r.Value1.XAdvance if r.Value1 else 0
                                        exact[names[g1] + names[r.SecondGlyph]] = round((v or 0) / GRID, 1)
                            continue
                        if getattr(st, 'Format', None) != 2:
                            continue
                        for g1, c1 in st.ClassDef1.classDefs.items():
                            if g1 not in names:
                                continue
                            for g2, c2 in st.ClassDef2.classDefs.items():
                                if g2 not in names:
                                    continue
                                v = st.Class1Record[c1].Class2Record[c2].Value1
                                if v is not None and v.XAdvance:
                                    kern[names[g1] + names[g2]] = round(v.XAdvance / GRID, 1)
            kern.update(exact)
            kern = {k: v for k, v in kern.items() if v}
            size = sum(len(v) for v in d.values())
            total += size
            print(f'{cls}: {len(d)} glyphs, {size} chars of paths, {len(kern)} kerning pairs', file=sys.stderr)
            lines.append(f'  {cls}: {json.dumps({"adv": adv, "kern": kern, "d": d}, ensure_ascii=False, separators=(",", ":"))},')
    lines.append('}')
    Path(sys.argv[1]).write_text('\n'.join(lines) + '\n')
    print(f'total {total} chars of paths', file=sys.stderr)


if __name__ == '__main__':
    main()
